def css_for(a, cta_bg_url):
    css = CSS_TMPL
    pal = PALETTES[a["palette"]]
    for k, role in BASE.items():
        css = css.replace(k, pal[role])
    css = css.replace("object-position:78% 35%", "object-position:" + a["profile"]["pos"])
    if cta_bg_url:
        css = css.replace("__CTA_BG__", cta_bg_url)
    else:
        css = css.replace(",url('__CTA_BG__')", "")
    return css + EXTRA_CSS


def placeholder_svg(label):
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="800"><rect width="100%" height="100%" fill="#e6e6e6"/>'
           '<text x="50%" y="50%" font-size="44" text-anchor="middle" fill="#888" font-family="sans-serif">'
           + html.escape("写真待ち：" + label) + '</text></svg>')
    from urllib.parse import quote
    return "data:image/svg+xml;charset=utf-8," + quote(svg)


def build(a, mode):
    """mode='wp' → WordPress貼り付け用 / 'preview' → ローカル確認用"""
    def img(key, label=""):
        fn = a["images"].get(key)
        if fn and fn.startswith("http"):
            return fn
        if mode == "wp":
            return UPLOAD + (fn or f"{a['slug'].split('-',1)[1]}-{key}.jpg")
        if fn:
            return "../img/" + a["slug"].split("-", 1)[1] + "/" + fn
        return placeholder_svg(label or key)

    def missing(key):
        return key not in a["images"]

    out = ['<div class="sd-article">', "<style>", css_for(a, img(a["cta"]["bg"]) if not missing(a["cta"]["bg"]) or mode == "preview" else None).rstrip("\n"), "</style>", ""]
    for p in a["lead"]:
        out.append(f'<p class="sd-lead">{mark(p)}</p>')
    pf = a["profile"]
    if missing(pf["img"]):
        out.append("<!-- 📷 写真待ち：プロフィール写真（正方形に近い顔写真） -->")
    out += ['<div class="sd-profile">',
            f'  <img src="{img(pf["img"], "プロフィール")}" alt="{html.escape(pf["alt"])}">',
            '  <div class="sd-pf-body">',
            f'    <div class="sd-pf-name">{html.escape(pf["name"])}</div>',
            f'    <div class="sd-pf-nick">{html.escape(pf["nick"])}</div>',
            '    <div class="sd-pf-tags">' + "".join(f"<span>{html.escape(t)}</span>" for t in pf["tags"]) + "</div>",
            "  </div>", "</div>"]
    for q, blocks in a["qa"]:
        out.append(f'<h2 class="sd-q">{html.escape(q)}</h2>')
        for b in blocks:
            kind = b[0]
            if kind == "p":
                out.append(f"<p>{mark(b[1])}</p>")
            elif kind == "point":
                out.append(f'<div class="sd-point">{mark(b[1])}</div>')
            elif kind == "todo":
                out.append(f'<div class="sd-todo">{mark(b[1])}</div>')
            elif kind == "fig":
                _, key, alt, cap = b
                if missing(key):
                    out.append(f"<!-- 📷 写真待ち：{alt} -->")
                out += ['<figure class="sd-fig">',
                        f'  <img src="{img(key, alt)}" alt="{html.escape(alt)}" loading="lazy">',
                        f"  <figcaption>{html.escape(cap)}</figcaption>", "</figure>"]
    out.append('<h2 class="sd-q">読者に向けてメッセージをお願いします！</h2>')
    if a["message"]:
        out.append('<div class="sd-message">' + "<br><br>".join(mark(m) for m in a["message"]) + "</div>")
    else:
        out.append('<div class="sd-todo">【未記入】読者へのメッセージを本人に記入してもらってください。</div>')
    out += ['<div class="sd-related">', "  <h3>あわせて読みたい｜NIJINで挑戦する仲間の声</h3>"]
    for r in a["related"]:
        href, src, alt, t, desc = RELATED[r]
        out += [f'  <a href="{href}" class="sd-related-card">',
                f'    <img src="{src}" alt="{html.escape(alt)}" loading="lazy">',
                '    <div class="sd-rel-body">',
                f'      <p class="sd-rel-title">{html.escape(t)}</p>',
                f'      <p class="sd-rel-desc">{html.escape(desc)}</p>',
                "    </div>", "  </a>"]
    c = a["cta"]
    out += ["</div>", '<div class="sd-cta">', '  <div class="sd-cta__bg"></div>',
            f'  <span class="sd-cta__eyebrow">{html.escape(c["eyebrow"])}</span>',
            f'  <p>{c["text"]}</p>',
            f'  <a class="sd-btn" href="{c["href"]}">{html.escape(c["btn"])}</a>',
            "</div>", "</div>", ""]
    return "\n".join(out)


def card_html(a):
    c = a["card"]
    name_short = c["name"]
    age = f'        <p class="meta-age">{html.escape(c["age"])}</p>\n' if c["age"] else ""
    items = "\n".join(f'        <p class="meta-item">{html.escape(i)}</p>' for i in c["items"])
    eyecatch = UPLOAD + a["slug"].split("-", 1)[1] + "-eyecatch.png"
    full = a["profile"]["name"].split("（")[0].replace(" ", "")
    nick = c["name"].split("（")[1].rstrip("）")
    alt = f"{full}（{nick}）さん"
    return f"""  <!-- {name_short} -->
  <a href="https://nijin.co.jp/recruit/{a['slug']}/" class="employee-card" data-major="{c['major']}" data-minor="{c['minor']}">
    <div class="card-label">{html.escape(c['minor'])}</div>
    <div class="img-wrapper"><img src="{eyecatch}" alt="{html.escape(alt)}"></div>
    <div class="card-content">
      <h3 class="card-title">{html.escape(a['title'])}</h3>
      <div class="card-meta">
{items}
        <p class="meta-name"><strong>{html.escape(c['name'])}</strong></p>
{age}      </div>
    </div>
  </a>"""


